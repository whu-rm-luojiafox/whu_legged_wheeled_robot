"""Generate fixed-model data for the pinned official TinyMPC ADMM core.

Uses exact offline SciPy DARE, not the upstream snapshot exporter: at the
pinned commit that exporter does not match TinyCache/TinyWorkspace layouts.
Official src/ remains pristine; all runtime adaptations live in port/.
Run: python tools/chassis/mpc/generate_solver.py
"""
from pathlib import Path
import argparse
import difflib
import hashlib
import json
import shutil
import urllib.request
import numpy as np
from scipy.linalg import solve_discrete_are

ROOT = Path(__file__).resolve().parents[3]
VENDOR = ROOT / "third_party/tinympc"
OUT = ROOT / "src/components/controller/chassis_mpc/mpc_generated"
COMMIT = "023f36bd5b27267e1a96ed47a774d120b5707f13"


def prepare_port():
    port = VENDOR / "port"
    port.mkdir(exist_ok=True)
    patches = []
    for name in ["admm.cpp", "admm.hpp", "types.hpp", "rho_benchmark.hpp"]:
        old = (VENDOR / "src/tinympc" / name).read_text(encoding="utf-8")
        new = old
        if name == "types.hpp":
            new = new.replace("typedef double tinytype;  // should be double if you want to generate code",
                              "#ifdef WHU_TINY_FLOAT\ntypedef float tinytype;\n#else\ntypedef double tinytype;\n#endif")
        if name == "admm.cpp":
            # Q/R in upstream workspace include rho. At a fixed point the
            # tracking linear term must use ORIGINAL Q/R, not Q+rho/R+rho.
            new = new.replace("solver->work->Q.array());", "(solver->work->Q.array() - solver->cache->rho));")
            new = new.replace("solver->work->R.array());", "(solver->work->R.array() - solver->cache->rho));")
            old_terminal = "-(solver->work->Xref.col(solver->work->N - 1).transpose().lazyProduct(solver->cache->Pinf))"
            new_terminal = "-((solver->cache->Pinf - solver->cache->rho * tinyMatrix::Identity(solver->work->nx, solver->work->nx)) * solver->work->Xref.col(solver->work->N - 1))"
            assert old_terminal in new
            new = new.replace(old_terminal, new_terminal)
            new = new.replace("    RhoAdapter adapter;", "#ifndef WHU_TINY_FIXED_RHO\n    RhoAdapter adapter;")
            new = new.replace("    // Initialize SOC slack variables if needed", "#endif\n    // Initialize SOC slack variables if needed")
            new = new.replace("        // Handle adaptive rho if enabled", "#ifndef WHU_TINY_FIXED_RHO\n        // Handle adaptive rho if enabled")
            new = new.replace("        // Check for whether cost is minimized", "#endif\n        // Check for whether cost is minimized")
            line = '            std::cout << "Solver converged in " << solver->work->iter << " iterations" << std::endl;'
            assert line in new
            new = new.replace(line, "#ifndef WHU_TINY_QUIET\n" + line + "\n#endif")
        (port / name).write_text(new, encoding="utf-8")
        patches.extend(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                       fromfile="src/tinympc/"+name, tofile="port/"+name))
    (port / "runtime.patch").write_text("".join(patches), encoding="utf-8")


def literal_matrix(name, value):
    value = np.asarray(value, dtype=float)
    if value.ndim == 1:
        value = value[:, None]
    values = ",\n".join("    " + ", ".join("(tinytype)"+format(x,".17g") for x in row) for row in value)
    return f"static const tinytype data_{name}[] = {{\n{values}\n}};\n", value.shape


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=Path, default=ROOT / "tools/chassis/model/generated/fixed_leg_L0p240_R0p240_Ts0p004000.json")
    args = parser.parse_args()
    model = json.loads(args.model.read_text(encoding="utf-8"))
    assert model["nx"] == 10 and model["nu"] == 4
    assert np.allclose(model["leg_lengths_m"], [.24,.24]) and model["sample_time_s"] == .004
    prepare_port()
    OUT.mkdir(exist_ok=True)
    A,B,Q,R = [np.asarray(model[k],float) for k in ["Ad","Bd","Q","R"]]
    rho = 1.0
    P = solve_discrete_are(A,B,Q+rho*np.eye(10),R+rho*np.eye(4))
    inv = np.linalg.inv(R+rho*np.eye(4)+B.T@P@B)
    K = inv@B.T@P@A
    matrices = {"A":A,"B":B,"Q":np.diag(Q)+rho,"R":np.diag(R)+rho,
                "P":P,"K":K,"inv":inv,"AmBKt":(A-B@K).T}
    definitions = []
    shapes = {}
    for name,value in matrices.items():
        declaration,shapes[name]=literal_matrix(name,value)
        definitions.append(declaration)
    header = '''// Generated by tools/chassis/mpc/generate_solver.py. Do not edit.
#pragma once
#include "admm.hpp"
#include <stdint.h>
void whu_tiny_init();
void whu_tiny_reset();
TinySolver *whu_tiny_solver();
uint32_t whu_tiny_payload_bytes();
'''
    source = '''// Generated fixed-model cache; official ADMM runs online.
#include "chassis_tiny_data.hpp"
#include "chassis_mpc_config.h"
static_assert(CHASSIS_MPC_KNOTS==8, "Regenerate for changed horizon");
static_assert(CHASSIS_MPC_RHO==1.0f, "Regenerate for changed rho");
static_assert(CHASSIS_MPC_TS_S==0.004f, "Regenerate for changed sample time");
static_assert(CHASSIS_MPC_LEG_LENGTH_M==0.24f, "Regenerate for changed legs");
static TinySolution solution;
static TinyCache cache;
static TinySettings settings;
static TinyWorkspace work;
static TinySolver solver={&solution,&settings,&cache,&work};
template<typename T> static void load(T& m,const tinytype* data,int rows,int cols) {
    m.resize(rows,cols);
    for(int r=0;r<rows;++r) for(int c=0;c<cols;++c) m(r,c)=data[r*cols+c];
}
'''+"".join(definitions)+"\nvoid whu_tiny_init() {\n"
    targets={"A":"work.Adyn","B":"work.Bdyn","Q":"work.Q","R":"work.R",
             "P":"cache.Pinf","K":"cache.Kinf","inv":"cache.Quu_inv","AmBKt":"cache.AmBKt"}
    for name,target in targets.items():
        rows,cols=shapes[name]
        source+=f"    load({target},data_{name},{rows},{cols});\n"
    source+='''    work.nx=10; work.nu=4; work.N=CHASSIS_MPC_KNOTS;
    cache.rho=CHASSIS_MPC_RHO;
    cache.APf=tinyVector::Zero(10); cache.BPf=tinyVector::Zero(4);
    work.fdyn=tinyVector::Zero(10);
    settings.abs_pri_tol=CHASSIS_MPC_TOL; settings.abs_dua_tol=CHASSIS_MPC_TOL;
    settings.max_iter=CHASSIS_MPC_MAX_ITER; settings.check_termination=1;
    settings.en_input_bound=1; settings.adaptive_rho=0;
    work.Xref=tinyMatrix::Zero(10,work.N);
    work.Uref=tinyMatrix::Zero(4,work.N-1);
    work.u_min=tinyMatrix::Zero(4,work.N-1);
    work.u_max=tinyMatrix::Zero(4,work.N-1);
    for(int i=0;i<4;++i) {
        tinytype limit=i<2?CHASSIS_MPC_WHEEL_LIMIT_NM:CHASSIS_MPC_HIP_LIMIT_NM;
        work.u_min.row(i).setConstant(-limit); work.u_max.row(i).setConstant(limit);
    }
'''
    dims={"x":(10,8),"u":(4,7),"q":(10,8),"r":(4,7),"p":(10,8),"d":(4,7),
          "v":(10,8),"vnew":(10,8),"z":(4,7),"znew":(4,7),"g":(10,8),"y":(4,7)}
    for name,(r,c) in dims.items(): source+=f"    work.{name}=tinyMatrix::Zero({r},{c});\n"
    source+='''    solution.x=tinyMatrix::Zero(10,work.N); solution.u=tinyMatrix::Zero(4,work.N-1);
}
void whu_tiny_reset() {
'''
    for name in dims: source+=f"    work.{name}.setZero();\n"
    source+='''    solution.solved=0; solution.iter=0; solution.x.setZero(); solution.u.setZero();
}
TinySolver *whu_tiny_solver() { return &solver; }
uint32_t whu_tiny_payload_bytes() {
    uint32_t elements=0;
'''
    for target in [*targets.values(),"work.fdyn","cache.APf","cache.BPf","work.Xref","work.Uref","work.u_min","work.u_max",*["work."+k for k in dims],"solution.x","solution.u"]:
        source+=f"    elements+=(uint32_t){target}.size();\n"
    source+='''    return elements*sizeof(tinytype);
}
'''
    (OUT/"chassis_tiny_data.hpp").write_text(header,encoding="utf-8")
    (OUT/"chassis_tiny_data.cpp").write_text(source,encoding="utf-8")
    metadata={"upstream_commit":COMMIT,"model_sha256":hashlib.sha256(args.model.read_bytes()).hexdigest(),
              "knots":8,"input_intervals":7,"sample_time_s":.004,"rho":rho,
              "Qf":(P-rho*np.eye(10)).tolist(),"cache_dare_relative_residual":float(np.linalg.norm(P-(Q+rho*np.eye(10)+A.T@P@A-A.T@P@B@K))/np.linalg.norm(P)),
              "generation":"SciPy offline augmented DARE + official TinyMPC runtime structs",
              "upstream_codegen_used":False,"adaptive_rho":False,"actuator_enabled":False}
    (OUT/"manifest.json").write_text(json.dumps(metadata,indent=2),encoding="utf-8")
    print("Generated",OUT,"DARE residual",metadata["cache_dare_relative_residual"])

if __name__=="__main__": main()

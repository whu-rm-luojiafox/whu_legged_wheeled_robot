/* Inputs are measured virtual-leg lengths in metres. Output order follows
 * the balance model: [left wheel, right wheel, left leg, right leg]. */
void chassis_lqr_gain_calculate(float left_m, float right_m,
                                float gain[4][10])
{
    for (unsigned row = 0; row < 4; ++row) {
        for (unsigned column = 0; column < 10; ++column) {
            const unsigned index = column + row * 10;
            gain[row][column] = K_Fit[index][0]
                + K_Fit[index][1] * left_m
                + K_Fit[index][2] * right_m
                + K_Fit[index][3] * (left_m * left_m)
                + K_Fit[index][4] * (left_m * right_m)
                + K_Fit[index][5] * (right_m * right_m);
        }
    }
}
